/* Uji ringkasan lima lagu dan layar Pustaka lengkap. */
import { JSDOM } from 'jsdom';
import fs from 'node:fs';
import { indexedDB as fakeIDB } from 'fake-indexeddb';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
process.chdir(path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..'));
const dom = new JSDOM(fs.readFileSync('docs/index.html', 'utf8'), { url: 'https://x.test/', pretendToBeVisual: true });
const { window: w } = dom; w.indexedDB = fakeIDB;
for (const k of ['document', 'HTMLElement', 'Node', 'Range', 'MouseEvent', 'Event', 'InputEvent', 'localStorage', 'Image', 'Blob']) if (w[k] !== undefined) globalThis[k] = w[k];
globalThis.window = w; globalThis.self = w; globalThis.indexedDB = w.indexedDB;
globalThis.addEventListener = w.addEventListener.bind(w);
Object.defineProperty(globalThis, 'navigator', { value: w.navigator, configurable: true });
w.URL.createObjectURL = () => 'blob:x/1'; w.URL.revokeObjectURL = () => {}; globalThis.URL = w.URL;
w.HTMLCanvasElement.prototype.getContext = () => null;
const root = process.cwd();
const version = fs.readFileSync('docs/app.js', 'utf8').match(/\?v=(\d+)/)[1];
await import(`${root}/docs/app.js?v=${version}`);
const router = await import(`${root}/docs/core/router.js?v=${version}`);
const S = await import(`${root}/docs/musik/simpan.js?v=${version}`);
const tunggu = (ms = 100) => new Promise(r => setTimeout(r, ms));
let gagal = 0;
function cek(n, ok) { console.log(`${ok ? 'OK  ' : 'FAIL'} ${n}`); if (!ok) gagal++; }
await tunggu();
for (let i = 1; i <= 8; i++) await S.tambahLagu(new Blob([new Uint8Array(8)], { type: 'audio/mpeg' }), { nama: `Lagu ${i}`, durasi: 30 });
router.go('musik'); await tunggu();
const ringkas = document.querySelectorAll('.mus-pustaka .mus-item-judul');
cek('layar Musik membatasi pustaka ringkas menjadi lima lagu', ringkas.length === 5);
cek('tombol Lihat semua tersedia bila pustaka lebih dari lima', !!document.querySelector('[data-mus="pustaka"]') && document.querySelector('[data-mus="pustaka"]').textContent.includes('8'));
document.querySelector('[data-mus="pustaka"]').click(); await tunggu();
cek('tombol membuka layar Pustaka lagu terpisah', router.cur === 'musik-pustaka' && !!document.querySelector('.mus-pustaka-lengkap'));
cek('layar Pustaka menampilkan seluruh delapan lagu', document.querySelectorAll('.mus-pustaka-lengkap .mus-item-judul').length === 8);
const cari = document.querySelector('[data-pustaka-cari]');
cari.value = 'Lagu 7'; cari.dispatchEvent(new w.Event('input', { bubbles: true }));
const tersaring = [...document.querySelectorAll('[data-pustaka-baris]')].filter(x => !x.hidden);
cek('pencarian memfilter lagu dalam pustaka lengkap', tersaring.length === 1 && tersaring[0].textContent.includes('Lagu 7'));
cari.value = 'tidak ada'; cari.dispatchEvent(new w.Event('input', { bubbles: true }));
cek('pencarian kosong memberi pesan tidak ditemukan', document.querySelector('[data-pustaka-hasil]')?.hidden === false);
document.getElementById('back').click(); await tunggu();
cek('tombol kembali dari pustaka kembali ke Musik', router.cur === 'musik');
console.log(gagal ? `\n${gagal} GAGAL` : '\nSemua uji musik-pustaka-layar LOLOS');
dom.window.close(); process.exit(gagal ? 1 : 0);
