/* Regresi UI Tahap 1: simpan acara mandiri, tampilkan di bulan/panel tanggal,
   edit/hapus, saklar lapisan, dan persistensi snapshot. */
import { JSDOM } from 'jsdom';
import { indexedDB as fakeIDB } from 'fake-indexeddb';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
process.chdir(path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..'));
const root = process.cwd();
const version = fs.readFileSync('docs/app.js', 'utf8').match(/\?v=(\d+)/)[1];
const dom = new JSDOM(fs.readFileSync('docs/index.html', 'utf8'), { url: 'https://hara.test/', pretendToBeVisual: true });
const { window: w } = dom;
w.indexedDB = fakeIDB;
for (const k of ['document','getSelection','HTMLElement','Node','Range','MouseEvent','KeyboardEvent','Event','InputEvent','localStorage','Image','NodeFilter','File','Blob','FormData'])
  if (w[k] !== undefined) globalThis[k] = w[k];
globalThis.window = w; globalThis.self = w; globalThis.indexedDB = w.indexedDB;
globalThis.addEventListener = w.addEventListener.bind(w);
Object.defineProperty(globalThis, 'navigator', { value: w.navigator, configurable: true });
w.URL.createObjectURL = () => 'blob:hara/test'; w.URL.revokeObjectURL = () => {}; globalThis.URL = w.URL;
const st = (...p) => import(`${root}/docs/${p.join('/')}?v=${version}`);
await st('app.js');
const { state, simpanTahan } = await st('core/store.js');
const router = await st('core/router.js');
const d = w.document;
const sleep = (ms = 60) => new Promise(r => setTimeout(r, ms));
let failed = 0, total = 0;
const check = (name, yes, detail = '') => { total++; if (!yes) { failed++; console.error('FAIL', name, detail); } else console.log('ok', name); };
const now = new Date();
const iso = `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, '0')}-${String(now.getDate()).padStart(2, '0')}`;
state.acaraKalender = [];
router.go('task'); await sleep();
check('kalender menampilkan kontrol lapisan tenggat, acara, jurnal', d.querySelectorAll('[data-kal-lapisan]').length === 3);
const form = d.querySelector('[data-kal-acara-form]');
check('form tambah acara tampil di panel tanggal', !!form);
form.querySelector('[name=judul]').value = 'Design review';
form.querySelector('[name=kategori]').value = 'work';
form.querySelector('[name=tanggalMulai]').value = iso;
form.querySelector('[name=tanggalAkhir]').value = iso;
form.querySelector('[name=jamMulai]').value = '10:00';
form.querySelector('[name=jamAkhir]').value = '11:30';
form.querySelector('[name=zonaWaktu]').value = 'Asia/Makassar';
form.dispatchEvent(new w.Event('submit', { bubbles: true, cancelable: true }));
await sleep();
check('submit form valid memasukkan acara ke state', state.acaraKalender.length === 1);
check('acara mandiri tampil pada panel dan tanggal bulan', d.querySelector('.kal-acara-teks')?.textContent.includes('Design review') && d.querySelector('.kal-acara-titik'));
check('rentang jam dan zona waktu tertulis pada kartu acara', d.querySelector('.kal-acara-teks span')?.textContent.includes('Asia/Makassar'));
const layerAcara = d.querySelector('[data-kal-lapisan="acara"]');
layerAcara.checked = false;
layerAcara.dispatchEvent(new w.Event('change', { bubbles: true })); await sleep();
check('lapisan acara dapat disembunyikan tanpa menghapus data', state.acaraKalender.length === 1 && !d.querySelector('.kal-acara-teks'));
d.querySelector('[data-kal-lapisan="acara"]').checked = true;
d.querySelector('[data-kal-lapisan="acara"]').dispatchEvent(new w.Event('change', { bubbles: true })); await sleep();
const id = state.acaraKalender[0]?.id;
const klik = el => el?.dispatchEvent(new w.MouseEvent('click', { bubbles: true, cancelable: true, view: w }));
check('tombol edit dan hapus tersedia di kartu acara', !!d.querySelector(`[data-kal-edit="${id}"]`) && !!d.querySelector(`[data-kal-hapus="${id}"]`));
klik(d.querySelector(`[data-kal-edit="${id}"]`)); await sleep();
check('form edit terbuka dengan judul yang sudah terisi', d.querySelector('[data-kal-acara-form] input[name=judul]')?.value === 'Design review');
klik(d.querySelector(`[data-kal-hapus="${id}"]`)); await sleep();
check('hapus menghilangkan acara dari state dan kalender', state.acaraKalender.length === 0 && !d.querySelector('.kal-acara-teks'));
klik(d.querySelector('#toast .toast-a')); await sleep();
check('aksi urungkan memulihkan acara yang terhapus', state.acaraKalender.some(a => a.id === id));
klik(d.querySelector(`[data-kal-hapus="${id}"]`)); await sleep();
check('acara dapat dihapus lagi setelah urung', state.acaraKalender.length === 0);
state.acaraKalender.push({ id: 'persist-1', judul: 'Persistensi', sepanjangHari: true, tanggalMulai: iso, tanggalAkhir: iso, zonaWaktu: 'UTC', kategori: 'personal', dibuat: 1, diubah: 1 });
const dataIO = await st('notes/data-io.js');
const cadangan = await dataIO.cadanganJson();
const pratinjau = await dataIO.siapImporJson(cadangan.teks);
check('cadangan JSON membawa acara kalender dan pratinjau menormalkannya', pratinjau.acaraKalender?.[0]?.id === 'persist-1');
state.acaraKalender = [];
await dataIO.terapkanImporJson(pratinjau, 'timpa');
check('pemulihan mode timpa mengembalikan acara mandiri', state.acaraKalender[0]?.id === 'persist-1');
check('snapshot acara kalender berhasil ditulis', await simpanTahan());
const raw = await (await st('core/db-catatan.js')).muatMentah();
check('acara kalender ikut tersimpan di IndexedDB bersama catatan', JSON.parse(raw).acaraKalender?.[0]?.id === 'persist-1');

console.log(`\nHasil: ${total - failed}/${total} lulus`);
process.exitCode = failed ? 1 : 0;
